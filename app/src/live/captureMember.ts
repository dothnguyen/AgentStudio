// Operator-only capture: npm run capture:member (Windows; needs the Electron binary).
// Renders the member details page and its three dialogs at 1440x1180 and writes
// them to design/teams-member-detail-v7/captures/.
import { app, BrowserWindow, session } from 'electron';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';

const WIDTH = 1440;
const HEIGHT = 1180;
const READY_TIMEOUT_MS = 20000;
const MEMBER_ID = 'lead';

const appDir = path.resolve(__dirname, '..', '..');
const pagePath = path.join(appDir, 'dist', 'capture', 'index.html');
const outDir = path.resolve(appDir, '..', 'design', 'teams-member-detail-v7', 'captures');

const MODES = [
  { mode: 'member', file: 'overview.png', dialog: null },
  { mode: 'edit-member', file: 'edit-member.png', dialog: 'Edit member settings' },
  { mode: 'edit-agents', file: 'edit-agents.png', dialog: 'Edit agent options' },
  { mode: 'edit-instructions', file: 'edit-instructions.png', dialog: 'Edit role instructions' },
] as const;

app.commandLine.appendSwitch('force-device-scale-factor', '1');
// Closing one capture window must not quit the app before the next mode runs.
app.on('window-all-closed', () => undefined);

app.whenReady().then(capture).then(
  (code) => app.exit(code),
  (error: unknown) => {
    console.error(`capture:member: ${error instanceof Error ? error.message : String(error)}`);
    app.exit(1);
  },
);

async function evaluate<T>(win: BrowserWindow, script: string): Promise<T> {
  return win.webContents.executeJavaScript(script) as Promise<T>;
}

async function waitFor(win: BrowserWindow, script: string, label: string): Promise<void> {
  const deadline = Date.now() + READY_TIMEOUT_MS;
  for (;;) {
    if (await evaluate<boolean>(win, script)) return;
    if (Date.now() >= deadline) throw new Error(`${label} was not ready within 20 s.`);
    await new Promise<void>((resolve) => { setTimeout(resolve, 100); });
  }
}

async function captureOne(win: BrowserWindow, mode: string, file: string, dialog: string | null): Promise<void> {
  await win.loadFile(pagePath);
  await waitFor(win, "document.documentElement.dataset.captureReady === 'true'", 'the Teams capture page');
  await evaluate(win, `document.querySelector('[data-member-row="${MEMBER_ID}"]')?.click()`);
  await waitFor(win, "document.getElementById('teams-member-detail-title') !== null", 'the member details page');
  if (dialog !== null) {
    await evaluate(win, `document.querySelector('button[aria-label="${dialog}"]')?.click()`);
    await waitFor(win, `document.querySelector('[role="dialog"]')?.textContent?.includes(${JSON.stringify(dialog === 'Edit role instructions' ? 'Edit TeamLead instructions' : dialog)}) === true`, `the ${dialog} dialog`);
  }
  await waitFor(win, "!document.body.textContent?.includes('Checking ticket permission…')", 'the ticket permission read');
  await evaluate(win, `(async () => { if ('fonts' in document) await document.fonts.ready; if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); await new Promise(resolve => setTimeout(resolve, 400)); return true; })()`);
  win.webContents.invalidate();
  const image = await win.webContents.capturePage({ x: 0, y: 0, width: WIDTH, height: HEIGHT });
  const size = image.getSize();
  const output = size.width === WIDTH && size.height === HEIGHT ? image : image.resize({ width: WIDTH, height: HEIGHT });
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, file), output.toPNG());
  console.log(`capture:member: wrote ${file} (${mode}).`);
}

async function capture(): Promise<number> {
  if (!fs.existsSync(pagePath)) {
    throw new Error('dist/capture/index.html is missing. Run "npm run capture:member", which builds it first.');
  }
  session.defaultSession.setPermissionRequestHandler((_wc, _perm, callback) => callback(false));
  const win = new BrowserWindow({
    width: WIDTH,
    height: HEIGHT,
    useContentSize: true,
    show: false,
    resizable: false,
    backgroundColor: '#111316',
    webPreferences: { contextIsolation: true, nodeIntegration: false, sandbox: true },
  });
  win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }));
  win.showInactive();
  try {
    for (const { mode, file, dialog } of MODES) await captureOne(win, mode, file, dialog);
  } finally {
    win.destroy();
  }
  // Pin the generated bytes so the capture test fails when an image is stale
  // or only partly regenerated, not merely when it stops being a PNG.
  const files = Object.fromEntries(MODES.map(({ file }) => {
    const hash = createHash('sha256').update(fs.readFileSync(path.join(outDir, file))).digest('hex');
    return [file, hash];
  }));
  fs.writeFileSync(path.join(outDir, 'manifest.json'), `${JSON.stringify({ width: WIDTH, height: HEIGHT, files }, null, 2)}\n`);
  console.log(`capture:member: wrote ${MODES.length} screenshots to design/teams-member-detail-v7/captures/.`);
  return 0;
}
