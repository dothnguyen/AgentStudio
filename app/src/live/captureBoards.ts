// Operator-only capture: npm run capture:boards (Windows; needs the Electron binary).
// Renders the real Current Phase board and the four ticket page variants and writes
// them to design/boards-v1/captures/.
import { app, BrowserWindow, session } from 'electron';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';

const WIDTH = 1440;
const READY_TIMEOUT_MS = 20000;

const appDir = path.resolve(__dirname, '..', '..');
const pagePath = path.join(appDir, 'dist', 'capture', 'index.html');
const outDir = path.resolve(appDir, '..', 'design', 'boards-v1', 'captures');

interface Mode {
  file: string;
  view: string;
  height: number;
}

const MODES: Mode[] = [
  { file: 'board.png', view: 'board', height: 1521 },
  { file: 'board-all-columns.png', view: 'board-all', height: 1521 },
  { file: 'ticket-working.png', view: 'ticket-working', height: 1345 },
  { file: 'ticket-waiting.png', view: 'ticket-waiting', height: 1300 },
  { file: 'ticket-blocked.png', view: 'ticket-blocked', height: 1300 },
  { file: 'ticket-done.png', view: 'ticket-done', height: 1300 },
];

app.commandLine.appendSwitch('force-device-scale-factor', '1');
// Closing one capture window must not quit the app before the next mode runs.
app.on('window-all-closed', () => undefined);

app.whenReady().then(capture).then(
  (code) => app.exit(code),
  (error: unknown) => {
    console.error(`capture:boards: ${error instanceof Error ? error.message : String(error)}`);
    app.exit(1);
  },
);

async function evaluate<T>(win: BrowserWindow, script: string): Promise<T> {
  return win.webContents.executeJavaScript(script) as Promise<T>;
}

async function waitFor(win: BrowserWindow, script: string, label: string): Promise<void> {
  const deadline = Date.now() + READY_TIMEOUT_MS;
  for (;;) {
    if (await evaluate<boolean>(win, script)) return;
    if (Date.now() >= deadline) throw new Error(`${label} was not ready within 20 s.`);
    await new Promise<void>((resolve) => { setTimeout(resolve, 100); });
  }
}

async function captureOne(win: BrowserWindow, mode: Mode): Promise<void> {
  await win.setContentSize(WIDTH, mode.height);
  await win.loadFile(pagePath, { query: { app: 'boards', view: mode.view } });
  await waitFor(win, "document.documentElement.dataset.captureReady === 'true'", `the ${mode.view} capture page`);
  await evaluate(win, `(async () => { if ('fonts' in document) await document.fonts.ready; if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); await new Promise(resolve => setTimeout(resolve, 400)); return true; })()`);
  win.webContents.invalidate();
  const image = await win.webContents.capturePage({ x: 0, y: 0, width: WIDTH, height: mode.height });
  const size = image.getSize();
  const output = size.width === WIDTH && size.height === mode.height
    ? image
    : image.resize({ width: WIDTH, height: mode.height });
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, mode.file), output.toPNG());
  console.log(`capture:boards: wrote ${mode.file}.`);
}

async function capture(): Promise<number> {
  if (!fs.existsSync(pagePath)) {
    throw new Error('dist/capture/index.html is missing. Run "npm run capture:boards", which builds it first.');
  }
  session.defaultSession.setPermissionRequestHandler((_wc, _perm, callback) => callback(false));
  const win = new BrowserWindow({
    width: WIDTH,
    height: MODES[0]!.height,
    useContentSize: true,
    show: false,
    resizable: false,
    backgroundColor: '#111316',
    webPreferences: { contextIsolation: true, nodeIntegration: false, sandbox: true },
  });
  win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }));
  win.showInactive();
  try {
    for (const mode of MODES) await captureOne(win, mode);
  } finally {
    win.destroy();
  }
  // Pin the generated bytes so the capture test fails when an image is stale
  // or only partly regenerated, not merely when it stops being a PNG.
  const files = Object.fromEntries(MODES.map(({ file, height }) => {
    const bytes = fs.readFileSync(path.join(outDir, file));
    return [file, { width: WIDTH, height, sha256: createHash('sha256').update(bytes).digest('hex') }];
  }));
  fs.writeFileSync(path.join(outDir, 'manifest.json'), `${JSON.stringify({ width: WIDTH, files }, null, 2)}\n`);
  console.log(`capture:boards: wrote ${MODES.length} screenshots to design/boards-v1/captures/.`);
  return 0;
}
