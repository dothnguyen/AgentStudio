// @vitest-environment jsdom
import * as fs from 'node:fs';
import * as path from 'node:path';
import { createHash } from 'node:crypto';
import { afterEach, describe, expect, it } from 'vitest';
import { cleanup } from '@testing-library/react';
import { openRoutingSection } from '../capture/RoutingCaptureApp';
import { routingV1Overview, routingV1Roles, routingV1Settings } from '../capture/routingV1Fixture';

const appDir = path.join(__dirname, '..');
const designDir = path.join(appDir, '..', 'design', 'routing-v1');
const captureDir = path.join(designDir, 'captures');
const read = (file: string) => fs.readFileSync(file, 'utf8');

afterEach(() => {
  cleanup();
  delete document.documentElement.dataset.captureReady;
  delete document.documentElement.dataset.captureError;
});

function pngSize(file: string): { width: number; height: number } {
  const data = fs.readFileSync(file);
  expect([...data.subarray(0, 8)]).toEqual([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  return { width: data.readUInt32BE(16), height: data.readUInt32BE(20) };
}

function sha256(file: string): string {
  return createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

describe('routing v1 capture fixture', () => {
  it('matches the design sample rules, statuses, roles and running team', () => {
    const settings = routingV1Settings();
    expect(settings.statuses.map(status => status.name)).toEqual([
      'Backlog', 'Dev ready', 'Merge ready', 'Merge conflict', 'Plan merge ready', 'Plan merge conflict',
      'Review ready', 'QA ready', 'Needs escalation', 'Refine ready', 'Unpack ready', 'Done',
    ]);
    expect(settings.rules.map(rule => rule.status)).toEqual([
      'merge-ready', 'plan-merge-ready', 'merge-conflict', 'plan-merge-conflict', 'review-ready',
      'qa-ready', 'need-escalate', 'dev-ready', 'refine-ready', 'unpack-ready',
    ]);
    expect(settings.actionRules.map(rule => rule.status)).toEqual(['merge-ready', 'plan-merge-ready']);
    expect(settings.rules.filter(rule => rule.protected).map(rule => rule.status)).toEqual(['merge-conflict', 'plan-merge-conflict']);
    expect(settings.rules[4]!.onFailureLimit).toEqual({ count: 3, status: 'need-escalate' });
    expect(routingV1Roles().items.map(role => role.id)).toEqual(['Developer', 'TeamLead', 'Reviewer', 'QA', 'SeniorDeveloper', 'ProductOwner']);
    expect(routingV1Overview().teams[0]!.members.map(member => member.role)).toEqual(['TeamLead', 'Developer', 'Developer', 'Reviewer', 'QA', 'SeniorDeveloper']);
    expect(routingV1Overview().teams[0]!.runtime.state).toBe('running');
  });

  it('opens Routing only from an enabled sidebar item', () => {
    expect(openRoutingSection(document.createElement('div'))).toBe(false);

    const nav = document.createElement('nav');
    nav.className = 'workspace-nav';
    const item = document.createElement('button');
    item.className = 'workflow-nav-item';
    const label = document.createElement('span');
    label.className = 'nav-label';
    label.textContent = 'Routing';
    item.append(label);
    let clicks = 0;
    item.addEventListener('click', () => { clicks += 1; });
    nav.append(item);
    const root = document.createElement('div');
    root.append(nav);

    expect(openRoutingSection(root)).toBe(true);
    expect(clicks).toBe(1);
    item.disabled = true;
    expect(openRoutingSection(root)).toBe(false);
  });

  it('wires the routing capture command and names each state like its design file', () => {
    const pkg = JSON.parse(read(path.join(appDir, 'package.json'))) as { scripts: Record<string, string> };
    expect(pkg.scripts['capture:routing']).toContain('electron dist/live/captureRouting.js');
    const capture = read(path.join(appDir, 'src/live/captureRouting.ts'));
    expect(capture).toContain("'design', 'routing-v1', 'captures'");
    for (const name of ['overview', 'edit-rule', 'edit-action-rule', 'new-rule', 'remove-rule', 'worktrees']) {
      expect(capture).toContain(`file: '${name}.png'`);
    }
    expect(capture).toContain("query: { app: 'routing' }");
  });
});

// The screenshots are generated by the operator on a machine with Electron's
// system libraries (npm run capture:routing). When they are present this pins
// the bytes; when they are absent the capture work is still reported as not run.
const manifestPath = path.join(captureDir, 'manifest.json');
const hasCaptures = fs.existsSync(manifestPath);

describe.skipIf(!hasCaptures)('routing v1 capture evidence', () => {
  const names = ['overview', 'edit-rule', 'edit-action-rule', 'new-rule', 'remove-rule', 'worktrees'];
  const manifest = hasCaptures
    ? JSON.parse(read(manifestPath)) as { width: number; height: number; files: Record<string, string> }
    : { width: 0, height: 0, files: {} };

  it.each(names)('captures/%s.png is a real screenshot matching its checksum', (name) => {
    const file = path.join(captureDir, `${name}.png`);
    expect(fs.existsSync(file), `${file} is missing`).toBe(true);
    expect(fs.statSync(file).size).toBeGreaterThan(10_000);
    expect(pngSize(file)).toEqual({ width: manifest.width, height: manifest.height });
    expect(sha256(file)).toBe(manifest.files[`${name}.png`]);
  });

  it('keeps the design size for every capture', () => {
    for (const name of names) {
      expect(pngSize(path.join(captureDir, `${name}.png`))).toEqual(pngSize(path.join(designDir, `${name}.png`)));
    }
  });
});
