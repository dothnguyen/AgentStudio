import { existsSync, readFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

const appDir = resolve(__dirname, '..');
const designDir = resolve(appDir, '..', 'design', 'teams-member-detail-v7');
const captureDir = resolve(designDir, 'captures');
const read = (absolutePath: string): string => readFileSync(absolutePath, 'utf8');

function pngSize(file: string): { width: number; height: number } {
  const data = readFileSync(file);
  expect([...data.subarray(0, 8)]).toEqual([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  return { width: data.readUInt32BE(16), height: data.readUInt32BE(20) };
}

function sha256(file: string): string {
  return createHash('sha256').update(readFileSync(file)).digest('hex');
}

/**
 * T-111 "Done when": the member page and its three dialogs have captures in
 * design/teams-member-detail-v7/captures/ named like the design files.
 * The manifest pins the generated bytes, so a wrong or partially regenerated
 * screenshot fails instead of passing on its PNG header alone.
 */
describe('member details v7 capture evidence', () => {
  const manifest = JSON.parse(read(resolve(captureDir, 'manifest.json'))) as {
    width: number;
    height: number;
    files: Record<string, string>;
  };

  it.each(['overview', 'edit-member', 'edit-agents', 'edit-instructions'])('captures/%s.png is a real 1440x1180 screenshot matching its checksum', (name) => {
    const file = resolve(captureDir, `${name}.png`);
    expect(existsSync(file), `${file} is missing`).toBe(true);
    expect(statSync(file).size).toBeGreaterThan(10_000);
    expect(pngSize(file)).toEqual({ width: manifest.width, height: manifest.height });
    expect(manifest.files[`${name}.png`]).toBeTruthy();
    expect(sha256(file)).toBe(manifest.files[`${name}.png`]);
  });

  it('names each capture like its design file and keeps the design size', () => {
    for (const name of ['overview', 'edit-member', 'edit-agents', 'edit-instructions']) {
      const design = resolve(designDir, `${name}.png`);
      expect(existsSync(design), `${design} is missing`).toBe(true);
      expect(pngSize(design), `${name}.png must use the design size`).toEqual({
        width: manifest.width,
        height: manifest.height,
      });
      expect(pngSize(resolve(captureDir, `${name}.png`))).toEqual(pngSize(design));
    }
  });

  it('wires the member capture command and documents the generated files', () => {
    const pkg = JSON.parse(read(resolve(appDir, 'package.json'))) as { scripts: Record<string, string> };
    expect(pkg.scripts['capture:member']).toContain('electron dist/live/captureMember.js');
    const capture = read(resolve(appDir, 'src/live/captureMember.ts'));
    expect(capture).toContain("'design', 'teams-member-detail-v7', 'captures'");
    for (const name of ['overview', 'edit-member', 'edit-agents', 'edit-instructions']) {
      expect(capture).toContain(`file: '${name}.png'`);
    }
    const readme = read(resolve(designDir, 'README.md'));
    expect(readme).toContain('npm --prefix app run capture:member');
    for (const name of ['overview.png', 'edit-member.png', 'edit-agents.png', 'edit-instructions.png']) {
      expect(readme).toContain(`captures/${name}`);
    }
  });
});
