// @vitest-environment jsdom
import * as fs from 'node:fs';
import * as path from 'node:path';
import { createHash } from 'node:crypto';
import { afterEach, describe, expect, it } from 'vitest';
import { cleanup, render, waitFor } from '@testing-library/react';
import { RolesCaptureApp, isRolesListReady, openRolesSection } from '../capture/RolesCaptureApp';
import { rolesCatalogV2 } from '../capture/rolesCatalogV2Fixture';

const appDir = path.join(__dirname, '..');
const designDir = path.join(appDir, '..', 'design', 'roles-catalog-v2');
const captureDir = path.join(designDir, 'captures');
const read = (absolutePath: string) => fs.readFileSync(absolutePath, 'utf8');

afterEach(() => {
  cleanup();
  delete document.documentElement.dataset.captureReady;
  delete document.documentElement.dataset.captureError;
});

function pngSize(file: string): { width: number; height: number } {
  const data = fs.readFileSync(file);
  expect([...data.subarray(0, 8)]).toEqual([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  return { width: data.readUInt32BE(16), height: data.readUInt32BE(20) };
}

function sha256(file: string): string {
  return createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

describe('roles v2 capture fixture', () => {
  it('matches the design sample roles, descriptions, skills and usage', () => {
    const catalog = rolesCatalogV2();
    expect(catalog.items.map(role => role.id)).toEqual(['TeamLead', 'Developer', 'SeniorDeveloper', 'QA', 'Reviewer', 'ProductOwner']);
    expect(catalog.items.map(role => role.skills.map(skill => skill.id))).toEqual([
      ['story-format', 'code-search'],
      ['story-format', 'python-testing', 'ts-testing'],
      ['story-format', 'python-testing', 'ts-testing'],
      ['code-search'],
      ['code-search'],
      ['story-format'],
    ]);
    expect(catalog.items[0]!.description).toBe('Team lead: unpacks features into phases, epics and stories; refines each story into a detailed technical plan before development and fixes it in place. Does not review code or merge.');
    expect(catalog.items[1]!.usage.members).toHaveLength(1);
    expect(catalog.items[5]!.usage.members).toHaveLength(0);
    expect(catalog.availableSkills).toEqual(['story-format', 'python-testing', 'code-search', 'ts-testing']);
    expect(catalog.items[0]!.instructions.path).toBe('roles/team-lead.md');
  });

  it('opens Roles in the real shell and marks the list ready', async () => {
    render(<RolesCaptureApp />);
    await waitFor(() => expect(document.documentElement.dataset.captureReady).toBe('true'), { timeout: 3000 });
    expect(isRolesListReady(document)).toBe(true);
    expect(document.querySelectorAll('[data-role-id]')).toHaveLength(6);
    expect(document.querySelector('[data-section="roles"]')?.textContent).toContain('TeamLead');
    expect(openRolesSection(document)).toBe(true);
  });
});

/**
 * T-115 "Done when": the list, role page and every dialog have captures in
 * design/roles-catalog-v2/captures/ named like the design files. The manifest
 * pins the generated bytes so a stale or partly regenerated screenshot fails.
 */
describe('roles v2 capture evidence', () => {
  const names = ['list', 'detail', 'edit-overview', 'edit-instructions', 'edit-skills', 'new-role', 'delete-role'];
  const manifest = JSON.parse(read(path.join(captureDir, 'manifest.json'))) as {
    width: number;
    height: number;
    files: Record<string, string>;
  };

  it.each(names)('captures/%s.png is a real 1440x1240 screenshot matching its checksum', (name) => {
    const file = path.join(captureDir, `${name}.png`);
    expect(fs.existsSync(file), `${file} is missing`).toBe(true);
    expect(fs.statSync(file).size).toBeGreaterThan(10_000);
    expect(pngSize(file)).toEqual({ width: manifest.width, height: manifest.height });
    expect(manifest.files[`${name}.png`]).toBeTruthy();
    expect(sha256(file)).toBe(manifest.files[`${name}.png`]);
  });

  it('names each capture like its design file and keeps the design size', () => {
    for (const name of names) {
      const design = path.join(designDir, `${name}.png`);
      expect(fs.existsSync(design), `${design} is missing`).toBe(true);
      expect(pngSize(design), `${name}.png must use the design size`).toEqual({
        width: manifest.width,
        height: manifest.height,
      });
      expect(pngSize(path.join(captureDir, `${name}.png`))).toEqual(pngSize(design));
    }
  });

  it('wires the roles capture command and documents the generated files', () => {
    const pkg = JSON.parse(read(path.join(appDir, 'package.json'))) as { scripts: Record<string, string> };
    expect(pkg.scripts['capture:roles']).toContain('electron dist/live/captureRoles.js');
    const capture = read(path.join(appDir, 'src/live/captureRoles.ts'));
    expect(capture).toContain("'design', 'roles-catalog-v2', 'captures'");
    for (const name of names) expect(capture).toContain(`file: '${name}.png'`);
    // Each capture must open the state it is named after, not just reuse a name.
    for (const mode of [
      "{ file: 'list.png', role: null, dialog: null }",
      "{ file: 'detail.png', role: 'TeamLead', dialog: null }",
      "{ file: 'edit-overview.png', role: 'TeamLead', dialog: { label: 'Edit overview', title: 'Edit overview' } }",
      "{ file: 'edit-instructions.png', role: 'TeamLead', dialog: { label: 'Edit shared instructions', title: 'Edit TeamLead instructions' } }",
      "{ file: 'edit-skills.png', role: 'TeamLead', dialog: { label: 'Edit skills', title: 'Edit skills' } }",
      "{ file: 'new-role.png', role: null, dialog: { label: 'New role', title: 'New role' } }",
      "{ file: 'delete-role.png', role: 'ProductOwner', dialog: { label: 'Delete role', title: 'Delete ProductOwner?' } }",
    ]) expect(capture).toContain(mode);
    const readme = read(path.join(designDir, 'README.md'));
    expect(readme).toContain('npm --prefix app run capture:roles');
    for (const name of names) expect(readme).toContain(`captures/${name}.png`);
  });

  it('lists_every_deliberate_difference_from_the_design', () => {
    // The captures cannot be pixel-identical to the static design files (real
    // data and the app sidebar differ), so the acknowledged differences are
    // documented next to them instead of being silently accepted.
    const readme = read(path.join(designDir, 'README.md'));
    for (const difference of [
      "the app's own sidebar",
      'Saved and Live · available',
      'ProductOwner',
      'Warnings and problems',
      'Save button disabled',
    ]) expect(readme, `README must list: ${difference}`).toContain(difference);
  });
});
